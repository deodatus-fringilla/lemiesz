// `pnpm db:snapshot` — writes data/baseline.sql, the committed starting content of every fresh database
// (docs/00_Architect_Exchange/Propozycja_Struktury_Korpusu.md v3.1, §3.1).
//
// Reads the master database (DATABASE_PATH, default ./data/lemiesz.db) READ-ONLY and dumps the content tables of
// the allowlist below as INSERT statements, sorted by table order and primary key, so `git diff` shows exactly which
// quotation, letter or card changed. Runtime tables (users, sessions, conversations, drafts, embeddings, FTS,
// _migrations) are never dumped. Refuses a master whose migrations are behind the migration files.
import Database from 'better-sqlite3';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Content tables, in an order that satisfies their foreign keys. Keep in sync with baseline.test.ts. */
export const BASELINE_TABLES = [
	'sources',
	'source_texts',
	'arguments',
	'argument_texts',
	'argument_sources',
	'correspondence_threads',
	'correspondence_letters',
	'media_assets',
	'campaign_posters',
	'argument_poster_links',
	'argument_media_links',
	'review_events'
];

/** @param {unknown} v */
function literal(v) {
	if (v === null || v === undefined) return 'NULL';
	if (typeof v === 'number' || typeof v === 'bigint') return String(v);
	if (Buffer.isBuffer(v)) return `X'${v.toString('hex')}'`;
	return `'${String(v).replace(/'/g, "''")}'`;
}

/**
 * @param {string} dbPath master database, opened read-only
 * @returns {string} the content of data/baseline.sql
 */
export function snapshot(dbPath) {
	const db = new Database(dbPath, { readonly: true, fileMustExist: true });
	try {
		const files = fs
			.readdirSync(path.join(ROOT, 'src/lib/server/migrations'))
			.filter((f) => f.endsWith('.sql'))
			.sort((a, b) => a.localeCompare(b));
		const latestFile = files.at(-1);
		const applied = /** @type {{ name: string }[]} */ (db.prepare('SELECT name FROM _migrations').all()).map((r) => r.name);
		const missing = files.filter((f) => !applied.includes(f));
		if (missing.length) {
			throw new Error(`${dbPath} has not applied ${missing.join(', ')}. Start the app once (pnpm dev) so it migrates, then snapshot.`);
		}

		const out = [
			`-- baseline-migration: ${latestFile}`,
			'-- data/baseline.sql: starting content of a fresh database. GENERATED by `pnpm db:snapshot`; do not edit by hand.',
			'-- Edit content in the app (or with a data migration), then snapshot again and commit this file with the change.',
			''
		];
		for (const table of BASELINE_TABLES) {
			const cols = /** @type {{ name: string; pk: number }[]} */ (db.prepare(`PRAGMA table_info(${table})`).all());
			const pk = cols.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk).map((c) => c.name);
			const order = (pk.length ? pk : cols.map((c) => c.name)).map((c) => `"${c}"`).join(', ');
			const names = cols.map((c) => c.name);
			const rows = /** @type {unknown[][]} */ (db.prepare(`SELECT * FROM ${table} ORDER BY ${order}`).raw().all());
			out.push(`-- ${table}: ${rows.length} row(s)`);
			for (const r of rows) out.push(`INSERT INTO ${table} (${names.join(', ')}) VALUES (${r.map(literal).join(', ')});`);
			out.push('');
		}
		return out.join('\n');
	} finally {
		db.close();
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const dbPath = process.env.DATABASE_PATH || path.join(ROOT, 'data/lemiesz.db');
	const target = path.join(ROOT, 'data/baseline.sql');
	try {
		const sql = snapshot(dbPath);
		fs.writeFileSync(target, sql);
		const counts = [...sql.matchAll(/^-- (\w+): (\d+) row/gm)].map((m) => `${m[1]} ${m[2]}`).join(', ');
		console.log(`db:snapshot — wrote ${path.relative(ROOT, target)} from ${dbPath}\n  ${counts}`);
	} catch (e) {
		console.error('db:snapshot FAILED:', /** @type {Error} */ (e).message);
		process.exit(1);
	}
}
